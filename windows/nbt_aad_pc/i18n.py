from contextvars import ContextVar

LANGUAGES = {'ru': 'Русский', 'en': 'English'}
_language = ContextVar('nbt_aad_language', default='ru')


@contextmanager
def using_language(language):
    token = _language.set(language)
    try:
        yield
    finally:
        _language.reset(token)


def tr(message, language=None):
    if (language or _language.get()) == 'en':
        return ENGLISH.get(message, message)
    return message


